/* Локальный humanize - «очеловечивания» «машинного» имени (только сертификаты), например: certificate_01.07.25.jpg → Сертификат · 01.07.2025 */
function humanize(name) {
  const m = name.match(/^certificate[_\-\s]+(\d{2})\.(\d{2})\.(\d{2})$/i);
  if (m) {
    const [, d, mo, y] = m;
    return `Сертификат · ${d}.${mo}.20${y}`;
  }
  return name
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^\w/, c => c.toUpperCase());
}

function getYearFromBase(base) {
  const m = base.match(/^(\d{4})/);
  return m ? +m[1] : null;
}

function getSpecFromBase(base) {
  return CERT_SPECIALTY[base] || 'other';
}

function renderCard(file) {
  const ext  = getExt(file.name);
  const base = getBase(file.name);
  const isPdf = PDF_EXT.includes(ext);
  const fileUrl = file.download_url
    || `https://raw.githubusercontent.com/${OWNER}/${REPO}/main/${FOLDER}/${encodePath(file.name)}`;

  const fullKey  = base + '.' + ext;
  const titleKey = (TITLES[fullKey] !== undefined) ? fullKey : base;
  const metaKey  = (META[fullKey]   !== undefined) ? fullKey : base;
  const hoursKey = (HOURS[fullKey]  !== undefined) ? fullKey : base;

  const title = TITLES[titleKey] || humanize(base);
  const meta  = META[metaKey] || '';
  const typeLabel = isPdf ? 'PDF' : 'IMG';
  const hours = HOURS[hoursKey];

  const thumb = isPdf
    ? `<div class="cert-pdf-placeholder">
         <div class="cert-pdf-icon">PDF</div>
         <div class="cert-pdf-label">Открыть документ</div>
       </div>`
    : `<img src="${fileUrl}" alt="${title}" loading="lazy">`;

  return `
    <a href="${fileUrl}" class="cert-card"
       data-file-url="${fileUrl}"
       data-file-type="${isPdf ? 'pdf' : 'image'}"
       data-file-title="${title.replace(/"/g, '&quot;')}">
      <span class="cert-type">${typeLabel}</span>
      ${hours ? `
        <span class="cert-hours" title="Объём программы">
          <span class="cert-hours__icon" aria-hidden="true">⏱</span>
          <span class="cert-hours__value">${hours} ${pluralHours(hours)}</span>
        </span>` : ''}
      <div class="cert-thumb">${thumb}</div>
      <div class="cert-info">
        <h3 class="cert-title">${title}</h3>
        ${meta ? `<p class="cert-meta">${meta}</p>` : ''}
      </div>
      <span class="cert-open" aria-hidden="true">↗</span>
    </a>
  `;
}

function filterCerts() {
  return allCerts.filter(f => {
    const base = getBase(f.name);
    const year = getYearFromBase(base);
    const spec = getSpecFromBase(base);
    if (activeYear !== 'all' && year !== +activeYear) return false;
    if (activeSpec !== 'all' && spec !== activeSpec)   return false;
    return true;
  });
}

function renderGallery() {
  const gallery = document.getElementById('gallery');
  if (!gallery) return;

  const filtered = filterCerts();
  gallery.innerHTML = filtered.length === 0
    ? `<div class="error">По выбранным фильтрам ничего не найдено.</div>`
    : filtered.map(renderCard).join('');

  updateStats(filtered);
  updateFilterBar();
}

function buildFilters() {
  const yearsListEl = document.getElementById('filter-years-list');
  const specsListEl = document.getElementById('filter-specs-list');
  if (!yearsListEl || !specsListEl) return;

  const yearStats = {};
  const specStats = {};

  allCerts.forEach(f => {
    const base  = getBase(f.name);
    const ext   = getExt(f.name);
    const year  = getYearFromBase(base);
    const spec  = getSpecFromBase(base);
    const fullKey = base + '.' + ext;
    const hoursKey = (HOURS[fullKey] !== undefined) ? fullKey : base;
    const h = Number(HOURS[hoursKey]) || 0;

    if (year) {
      if (!yearStats[year]) yearStats[year] = 0;
      yearStats[year] += h;
    }
    if (!specStats[spec]) specStats[spec] = 0;
    specStats[spec] += h;
  });

  // ----- ГОДЫ -----
  const years = Object.keys(yearStats).map(Number).sort((a, b) => b - a);
  const totalYearsHours = Object.values(yearStats).reduce((s, v) => s + v, 0);

  yearsListEl.innerHTML = `
    <button class="filter-item is-active" data-year="all">
      <span class="filter-item__label">Все годы</span>
      <span class="filter-item__hours">${totalYearsHours} ч</span>
    </button>
    ${years.map(y => `
      <button class="filter-item" data-year="${y}">
        <span class="filter-item__label">${y}</span>
        <span class="filter-item__hours">${yearStats[y]} ч</span>
      </button>
    `).join('')}
  `;
  yearsListEl.addEventListener('click', (e) => {
    const btn = e.target.closest('.filter-item');
    if (!btn || btn.classList.contains('is-empty')) return;

    const key = btn.dataset.year;
    const isAlreadyActive = btn.classList.contains('is-active');

    yearsListEl.querySelectorAll('.filter-item').forEach(b => b.classList.remove('is-active'));

    if (isAlreadyActive && key !== 'all') {
      activeYear = 'all';
      const allBtn = yearsListEl.querySelector('[data-year="all"]');
      if (allBtn) allBtn.classList.add('is-active');
    } else {
      btn.classList.add('is-active');
      activeYear = key === 'all' ? 'all' : +key;
    }
    renderGallery();
  });

  // ----- СПЕЦИАЛЬНОСТИ -----
  const allSpecs = Object.keys(SPECIALTIES).sort((a, b) => {
    const ha = specStats[a] || 0;
    const hb = specStats[b] || 0;
    return hb - ha;
  });
  const totalSpecsHours = Object.values(specStats).reduce((s, v) => s + v, 0);

  specsListEl.innerHTML = `
    <button class="filter-item is-active" data-spec="all">
      <span class="filter-item__label">Все</span>
      <span class="filter-item__hours">${totalSpecsHours} ч</span>
    </button>
    ${allSpecs.map(s => {
      const hours = specStats[s] || 0;
      return `
        <button class="filter-item ${hours === 0 ? 'is-empty' : ''}" data-spec="${s}">
          <span class="filter-item__label">${SPECIALTIES[s]}</span>
          <span class="filter-item__hours">${hours} ч</span>
        </button>`;
    }).join('')}
  `;
  specsListEl.addEventListener('click', (e) => {
    const btn = e.target.closest('.filter-item');
    if (!btn || btn.classList.contains('is-empty')) return;

    const key = btn.dataset.spec;
    const isAlreadyActive = btn.classList.contains('is-active');

    specsListEl.querySelectorAll('.filter-item').forEach(b => b.classList.remove('is-active'));

    if (isAlreadyActive && key !== 'all') {
      activeSpec = 'all';
      const allBtn = specsListEl.querySelector('[data-spec="all"]');
      if (allBtn) allBtn.classList.add('is-active');
    } else {
      btn.classList.add('is-active');
      activeSpec = key;
    }
    renderGallery();
  });
}

function updateStats(filteredCerts) {
  const yearsSumEl = document.getElementById('acc-years-sum');
  const specsSumEl = document.getElementById('acc-specs-sum');
  if (!yearsSumEl || !specsSumEl) return;

  let total = 0;
  filteredCerts.forEach(f => {
    const base = getBase(f.name);
    const fullKey = base + '.' + getExt(f.name);
    const hoursKey = (HOURS[fullKey] !== undefined) ? fullKey : base;
    total += Number(HOURS[hoursKey]) || 0;
  });

  yearsSumEl.textContent = total;
  specsSumEl.textContent = total;
}

