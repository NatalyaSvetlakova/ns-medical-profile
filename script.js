/* Загрузка и рендер галереи статей */
async function loadArticles() {
  const gallery = document.getElementById('gallery');
  if (!gallery) return;

  try {
    const res = await fetch('articles.json');
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const articles = await res.json();

    if (!articles.length) {
      gallery.innerHTML = '<div class="error">Пока нет статей.</div>';
      return;
    }

    articles.sort((a, b) => new Date(b.date) - new Date(a.date));

    gallery.innerHTML = articles.map(a => {
      const ext        = getExt(a.url || '');
      const isPdf      = ext === 'pdf';
      const isExternal = a.external === true;

      let typeLabel;
      if (isExternal)   typeLabel = 'ССЫЛКА';
      else if (isPdf)   typeLabel = 'PDF';
      else              typeLabel = 'IMG';

      const thumbSrc = a.image || ARTICLES_PLACEHOLDER;

      const cardAttrs = isExternal
        ? `href="${a.url}" target="_blank" rel="noopener" data-external="true"`
        : `href="${a.url}" data-file-url="${a.url}" data-file-type="${isPdf ? 'pdf' : 'image'}" data-file-title="${(a.title || '').replace(/"/g, '&quot;')}"`;

      return `
        <a ${cardAttrs} class="article-card">
          <span class="article-type ${isExternal ? 'is-link' : ''}">${typeLabel}</span>
          <span class="article-date-badge">
            <span aria-hidden="true">📅</span>
            <span>${shortDate(a.date)}</span>
          </span>
          <div class="article-thumb">
            <img src="${thumbSrc}" alt="${a.title}" loading="lazy"
                 onerror="this.onerror=null;this.src='${ARTICLES_PLACEHOLDER}'">
          </div>
          <div class="article-info">
            <h3 class="article-title">${a.title}</h3>
            ${a.description ? `<p class="article-meta">${a.description}</p>` : ''}
          </div>
          <span class="article-open" aria-hidden="true">↗</span>
        </a>
      `;
    }).join('');
  } catch (err) {
    gallery.innerHTML = `<div class="error">Не удалось загрузить статьи.<br>${err.message}</div>`;
  }
}

