function updateFilterBar() {
  const bar   = document.getElementById('filter-bar');
  const chips = document.getElementById('filter-chips');
  if (!bar || !chips) return;

  const chipsHtml = [];

  if (activeYear !== 'all') {
    chipsHtml.push(`
      <span class="filter-chip">
        Год: ${activeYear}
        <button class="filter-chip__close" data-clear="year" aria-label="Сбросить год">✕</button>
      </span>`);
  }
  if (activeSpec !== 'all') {
    const specName = SPECIALTIES[activeSpec] || activeSpec;
    chipsHtml.push(`
      <span class="filter-chip">
        ${specName}
        <button class="filter-chip__close" data-clear="spec" aria-label="Сбросить специализацию">✕</button>
      </span>`);
  }

  if (chipsHtml.length === 0) {
    bar.hidden = true;
  } else {
    bar.hidden = false;
    chips.innerHTML = chipsHtml.join('');
  }

  const accYears = document.getElementById('acc-years');
  const accSpecs = document.getElementById('acc-specs');
  if (accYears) accYears.classList.toggle('has-filter', activeYear !== 'all');
  if (accSpecs) accSpecs.classList.toggle('has-filter', activeSpec !== 'all');
}

function initFilterBarHandlers() {
  document.addEventListener('click', (e) => {
    const closeBtn = e.target.closest('.filter-chip__close');
    if (closeBtn) {
      const type = closeBtn.dataset.clear;
      if (type === 'year') {
        activeYear = 'all';
        document.querySelectorAll('#filter-years-list .filter-item').forEach(b => {
          b.classList.toggle('is-active', b.dataset.year === 'all');
        });
      } else if (type === 'spec') {
        activeSpec = 'all';
        document.querySelectorAll('#filter-specs-list .filter-item').forEach(b => {
          b.classList.toggle('is-active', b.dataset.spec === 'all');
        });
      }
      renderGallery();
      return;
    }

    if (e.target.closest('#filter-reset')) {
      activeYear = 'all';
      activeSpec = 'all';
      document.querySelectorAll('#filter-years-list .filter-item').forEach(b => {
        b.classList.toggle('is-active', b.dataset.year === 'all');
      });
      document.querySelectorAll('#filter-specs-list .filter-item').forEach(b => {
        b.classList.toggle('is-active', b.dataset.spec === 'all');
      });
      renderGallery();
    }
  });
}

async function loadCertificates() {
  const gallery = document.getElementById('gallery');
  if (!gallery) return;

  try {
    const res = await fetch('certificates.json');
    if (!res.ok) throw new Error('Не удалось загрузить манифест certificates.json');

    const files = await res.json();

    allCerts = files.map(f => ({
      name: f.name,
      type: 'file',
      download_url: f.url
    }));

    allCerts = allCerts.filter(f =>
      IMAGE_EXT.includes(getExt(f.name)) || PDF_EXT.includes(getExt(f.name))
    );

    if (allCerts.length === 0) {
      gallery.innerHTML = `<div class="error">В манифесте нет картинок или PDF.</div>`;
      return;
    }

    allCerts.sort((a, b) => {
      const ya = getYearFromBase(getBase(a.name)) || 0;
      const yb = getYearFromBase(getBase(b.name)) || 0;
      if (yb !== ya) return yb - ya;
      return b.name.localeCompare(a.name, 'ru');
    });

    buildFilters();
    renderGallery();
  } catch (err) {
    gallery.innerHTML = `<div class="error">Не удалось загрузить сертификаты.<br>${err.message}</div>`;
  }
}

function initCertModal() {
  const modal = document.getElementById('cert-modal');
  const body  = document.getElementById('cert-modal-body');
  if (!modal || !body) return;

  let lastFocused = null;

  function openModal(url, type, title) {
    lastFocused = document.activeElement;
    body.innerHTML = '';

    if (type === 'pdf') {
      body.innerHTML = `
        <div style="display:flex;flex-direction:column;align-items:center;gap:20px;padding:40px;color:#fff;text-align:center;font-family:-apple-system,sans-serif;">
          <div style="font-size:4rem;line-height:1;">📄</div>
          <div style="font-family:Georgia,serif;font-size:1.2rem;font-weight:600;max-width:400px;">${title || 'PDF-документ'}</div>
          <a href="${url}" target="_blank" rel="noopener" style="display:inline-block;padding:12px 28px;border-radius:100px;background:#fff;color:#b72e4a;font-weight:700;text-decoration:none;">Открыть PDF</a>
        </div>`;
    } else {
      const img = document.createElement('img');
      img.src = url;
      img.alt = title || '';
      body.appendChild(img);
    }

    modal.classList.add('is-open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.classList.add('modal-open');
  }

  function closeModal() {
    modal.classList.remove('is-open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
    setTimeout(() => { body.innerHTML = ''; }, 400);
    if (lastFocused && lastFocused.focus) lastFocused.focus();
  }

  document.addEventListener('click', (e) => {
    const card = e.target.closest('.cert-card');
    if (!card) return;
    const url = card.getAttribute('data-file-url');
    if (!url) return;

    e.preventDefault();
    e.stopPropagation();
    e.stopImmediatePropagation();

    const type  = card.getAttribute('data-file-type') || 'image';
    const title = card.getAttribute('data-file-title') || '';
    openModal(url, type, title);
  }, true);

  document.addEventListener('click', (e) => {
    if (e.target.closest('[data-close]')) {
      e.preventDefault();
      closeModal();
    }
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal.classList.contains('is-open')) closeModal();
  });
}

function initCertificatesPage() {
  initAccordions();
  initFilterBarHandlers();
  initCertModal();
  loadCertificates();
}

