function getExt(name) {
  const i = name.lastIndexOf('.');
  return i === -1 ? '' : name.slice(i + 1).toLowerCase();
}

function getBase(name) {
  const i = name.lastIndexOf('.');
  return i === -1 ? name : name.slice(0, i);
}

function encodePath(p) {
  return p.split('/').map(encodeURIComponent).join('/');
}

function shortDate(iso) {
  const d = new Date(iso);
  const dd = String(d.getDate()).padStart(2, '0');
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const yyyy = d.getFullYear();
  return `${dd}.${mm}.${yyyy}`;
}

function pluralHours(n) {
  const num = Math.abs(n) % 100;
  const lastDigit = num % 10;
  if (num >= 11 && num <= 14) return 'часов';
  if (lastDigit === 1) return 'час';
  if (lastDigit >= 2 && lastDigit <= 4) return 'часа';
  return 'часов';
}

/* Тема (общая для обеих страниц) */
function initTheme() {
  function toggleTheme(e) {
    if (e) e.stopPropagation();          // чтобы клик в модалке не уходил в data-close

    const current = document.documentElement.getAttribute('data-theme');
    const next    = current === 'dark' ? 'light' : 'dark';

    document.documentElement.classList.add('theme-transition-disabled');
    document.documentElement.setAttribute('data-theme', next);
    localStorage.setItem('theme', next);

    setTimeout(() => {
      document.documentElement.classList.remove('theme-transition-disabled');
    }, 50);
  }

  // Применяем сохранённую / системную тему при загрузке, если она ещё не была выставлена раньше (например, инлайновым скриптом в <head>)
  if (!document.documentElement.getAttribute('data-theme')) {
    const saved       = localStorage.getItem('theme');
    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    document.documentElement.setAttribute('data-theme', saved || (prefersDark ? 'dark' : 'light'));
  }

  const mainBtn  = document.getElementById('theme-toggle');
  const modalBtn = document.getElementById('modal-theme-toggle');
  if (mainBtn)  mainBtn.addEventListener('click', toggleTheme);
  if (modalBtn) modalBtn.addEventListener('click', toggleTheme);
}

/* Кнопка «НАВЕРХ» (глобальная, вне модалок) */
function initScrollTop() {
  const btn = document.getElementById('scroll-top');
  if (!btn) return;

  const updateVisibility = () => {
    btn.classList.toggle('is-visible', window.scrollY > 320);
  };
  window.addEventListener('scroll', updateVisibility, { passive: true });
  updateVisibility();

  btn.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });
}

