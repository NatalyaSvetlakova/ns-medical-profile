/* Модалка статьи с PDF.js */
function initArticleModal() {
  const modal = document.getElementById('article-modal');
  const body  = document.getElementById('article-modal-body');
  if (!modal || !body) return;

  let lastFocused = null;

  async function renderPdf(url, container) {
    try {
      const loadingTask = pdfjsLib.getDocument(url);
      const pdf = await loadingTask.promise;

      container.innerHTML = '';

      for (let pageNum = 1; pageNum <= pdf.numPages; pageNum++) {
        const page     = await pdf.getPage(pageNum);
        const viewport = page.getViewport({ scale: 1.5 });

        const canvas  = document.createElement('canvas');
        const context = canvas.getContext('2d');
        canvas.height = viewport.height;
        canvas.width  = viewport.width;

        container.appendChild(canvas);

        await page.render({ canvasContext: context, viewport }).promise;
      }
    } catch (err) {
      console.error('Ошибка PDF.js:', err);
      container.innerHTML = `
        <div class="error" style="color: var(--text);">
          Не удалось отобразить PDF.<br>
          <span style="font-size: 0.85rem; color: var(--text-muted);">${err.message}</span>
        </div>
      `;
    }
  }

  function openModal(url, type, title) {
    lastFocused = document.activeElement;
    body.innerHTML = '';
    body.scrollTop = 0;

    const btn = document.getElementById('modal-scroll-top');
    if (btn) btn.classList.remove('is-visible');

    if (type === 'pdf') {
      const pdfContainer = document.createElement('div');
      pdfContainer.className = 'pdf-js-container';
      pdfContainer.innerHTML = '<div class="pdf-loading">Загрузка PDF...</div>';
      body.appendChild(pdfContainer);
      renderPdf(url, pdfContainer);
    } else {
      const img = document.createElement('img');
      img.src = url;
      img.alt = title || '';
      body.appendChild(img);
    }

    modal.classList.add('is-open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.classList.add('modal-open');
  }

  function closeModal() {
    modal.classList.remove('is-open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
    setTimeout(() => { body.innerHTML = ''; }, 400);
    if (lastFocused && lastFocused.focus) lastFocused.focus();
  }

  // Клик по карточке статьи (внешние ссылки не перехватываем)
  document.addEventListener('click', (e) => {
    const card = e.target.closest('.article-card');
    if (!card) return;
    if (card.getAttribute('target') === '_blank') return;

    const url = card.getAttribute('data-file-url');
    if (!url) return;

    e.preventDefault();
    const type  = card.getAttribute('data-file-type') || 'image';
    const title = card.getAttribute('data-file-title') || '';
    openModal(url, type, title);
  }, true);

  // Закрытие
  document.addEventListener('click', (e) => {
    if (e.target.closest('[data-close]')) {
      e.preventDefault();
      closeModal();
    }
  });

  // Escape
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal.classList.contains('is-open')) closeModal();
  });

  // Кнопка «Наверх» внутри модалки
  const modalScrollBtn = document.getElementById('modal-scroll-top');
  if (modalScrollBtn) {
    body.addEventListener('scroll', () => {
      modalScrollBtn.classList.toggle('is-visible', body.scrollTop > 200);
    }, { passive: true });

    modalScrollBtn.addEventListener('click', () => {
      body.scrollTo({ top: 0, behavior: 'smooth' });
    });
  }
}

